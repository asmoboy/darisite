let LANG = "de";
try {
  LANG = localStorage.getItem("kreisel.lang") || (navigator.language?.startsWith("en") ? "en" : "de");
} catch {}
if (!I18N[LANG]) LANG = "de";

const t = (key) => I18N[LANG]?.[key] ?? I18N.de[key] ?? key;

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  const title = document.querySelector("title[data-i18n]");
  if (title) document.title = t(title.dataset.i18n);
  document.querySelectorAll("[data-lang]").forEach((el) => el.classList.toggle("is-active", el.dataset.lang === LANG));
}

function setLang(lang) {
  if (!I18N[lang] || lang === LANG) return;
  LANG = lang;
  try { localStorage.setItem("kreisel.lang", lang); } catch {}
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange"));
}

document.addEventListener("click", (e) => {
  const btn = e.target.closest("[data-lang]");
  if (!btn) return;
  setLang(btn.dataset.lang);
  document.getElementById("lang-menu")?.hidePopover?.();
});

applyI18n();
